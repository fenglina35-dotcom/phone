for name, lines in SECTIONS.items():
    path = DOCS / name
    if not path.is_file():
        raise RuntimeError(f"missing maintenance document: {path}")
    doc = Document(path)
    marker = lines[0]
    if any(marker in paragraph.text for paragraph in doc.paragraphs):
        continue
    doc.add_page_break()
    title = doc.add_paragraph()
    run = title.add_run(marker)
    run.bold = True
    for line in lines[1:]:
        doc.add_paragraph(line)
    doc.save(path)
    print(f"updated {path.name}")
